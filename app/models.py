"""Persistent state: accounts, devices, and versioned sync snapshots.

A snapshot is an opaque blob. The Flutter client decides what goes into it
(profile files plus the settings that must travel with them); the server only
guards who may write it and which revision a write was based on. That keeps
the wire format evolvable without a server migration every time the app learns
a new file.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    BigInteger,
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    LargeBinary,
    String,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .db import Base


def new_id() -> str:
    return uuid.uuid4().hex


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class User(Base):
    __tablename__ = "users"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    username: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    password_hash: Mapped[str] = mapped_column(String(255))
    disabled: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )

    devices: Mapped[list["Device"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )


class Device(Base):
    """One install of the app.

    ``key`` is generated by the client and reused across logins, so signing in
    again on the same machine updates its row instead of adding another one.
    """

    __tablename__ = "devices"
    __table_args__ = (UniqueConstraint("user_id", "key", name="uq_device_user_key"),)

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    key: Mapped[str] = mapped_column(String(64))
    name: Mapped[str] = mapped_column(String(64), default="")
    platform: Mapped[str] = mapped_column(String(32), default="")
    revoked: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )
    last_seen_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )

    user: Mapped[User] = relationship(back_populates="devices")


class Vault(Base):
    """The current snapshot for one account. Exactly one row per user."""

    __tablename__ = "vaults"

    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    revision: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    checksum: Mapped[str] = mapped_column(String(64), default="")
    size: Mapped[int] = mapped_column(Integer, default=0)
    content: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    device_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )


class VaultRevision(Base):
    """History kept so a bad push can be rolled back after a resync."""

    __tablename__ = "vault_revisions"
    __table_args__ = (
        UniqueConstraint("user_id", "revision", name="uq_vault_user_revision"),
    )

    id: Mapped[int] = mapped_column(BigInteger().with_variant(Integer, "sqlite"),
                                    primary_key=True, autoincrement=True)
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    revision: Mapped[int] = mapped_column(Integer, nullable=False)
    checksum: Mapped[str] = mapped_column(String(64), nullable=False)
    size: Mapped[int] = mapped_column(Integer, nullable=False)
    content: Mapped[bytes] = mapped_column(LargeBinary, nullable=False)
    device_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )


class Subscription(Base):
    """One airport subscription as the console sees it.

    The sync snapshot stays opaque on purpose, but this table is structured:
    the console lists subscriptions, links each to the airport's own site, and
    keeps the account bought there next to it. Stored values are returned only
    to the owner of the account over an authenticated request.
    """

    __tablename__ = "subscriptions"

    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_id)
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    name: Mapped[str] = mapped_column(String(64))
    url: Mapped[str] = mapped_column(String(2048), default="")
    site_url: Mapped[str] = mapped_column(String(512), default="")
    account: Mapped[str] = mapped_column(String(128), default="")
    password: Mapped[str] = mapped_column(String(256), default="")
    note: Mapped[str] = mapped_column(String(1024), default="")
    enabled: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    expire_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    traffic_used: Mapped[int] = mapped_column(BigInteger, default=0)
    traffic_total: Mapped[int] = mapped_column(BigInteger, default=0)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False
    )


class ProfileState(Base):
    """One subscription as it synced, keyed by the id the client generated.

    The snapshot table stores an opaque archive, which can only be replaced
    whole. A phone that deleted one subscription would otherwise resurrect it
    from any device that still had the archive. Keeping a row per profile,
    with a tombstone instead of a hard delete, is what makes add and remove
    both propagate.
    """

    __tablename__ = "profile_states"
    __table_args__ = (
        UniqueConstraint("user_id", "profile_id", name="uq_profile_state"),
    )

    id: Mapped[int] = mapped_column(
        BigInteger().with_variant(Integer, "sqlite"), primary_key=True, autoincrement=True
    )
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    profile_id: Mapped[str] = mapped_column(String(32))
    label: Mapped[str] = mapped_column(String(128), default="")
    url: Mapped[str] = mapped_column(String(2048), default="")
    type: Mapped[str] = mapped_column(String(16), default="file")
    content: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    checksum: Mapped[str] = mapped_column(String(64), default="")
    deleted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    sort_order: Mapped[int] = mapped_column(Integer, default=0)
    revision: Mapped[int] = mapped_column(Integer, default=0, index=True)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False
    )


class SyncRevision(Base):
    """Monotonic counter per account; clients page by it."""

    __tablename__ = "sync_revisions"

    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    revision: Mapped[int] = mapped_column(Integer, default=0, nullable=False)


class CloudItem(Base):
    """One uploadable thing: a profile, a DNS block, a rule, a script.

    Unlike the old snapshot this is a catalogue, not a mirror: a device only
    uploads what its owner asked it to, so "is this on the server" is a real
    question with a real answer.
    """

    __tablename__ = "cloud_items"
    __table_args__ = (
        UniqueConstraint("user_id", "kind", "item_id", name="uq_cloud_item"),
    )

    id: Mapped[int] = mapped_column(
        BigInteger().with_variant(Integer, "sqlite"), primary_key=True, autoincrement=True
    )
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    kind: Mapped[str] = mapped_column(String(16), index=True)
    item_id: Mapped[str] = mapped_column(String(64))
    title: Mapped[str] = mapped_column(String(128), default="")
    content: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    checksum: Mapped[str] = mapped_column(String(64), default="")
    uploader_device_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    deleted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    revision: Mapped[int] = mapped_column(Integer, default=0, index=True)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False
    )


class DeviceHolding(Base):
    """What a device reported holding at its last connection.

    The console answers "which devices still have this rule" from here, so the
    answer is only as fresh as the device's last sync.
    """

    __tablename__ = "device_holdings"

    device_id: Mapped[str] = mapped_column(String(32), primary_key=True)
    kind: Mapped[str] = mapped_column(String(16), primary_key=True)
    item_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    last_seen_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )


class CloudConflict(Base):
    """Two versions of one item that cannot both win.

    The server no longer pushes anything to devices, so a conflict is stored
    here and resolved by a person in the console: the device's upload is kept
    aside instead of overwriting the cloud copy.
    """

    __tablename__ = "cloud_conflicts"
    __table_args__ = (
        UniqueConstraint("user_id", "kind", "item_id", name="uq_cloud_conflict"),
    )

    id: Mapped[int] = mapped_column(
        BigInteger().with_variant(Integer, "sqlite"), primary_key=True, autoincrement=True
    )
    user_id: Mapped[str] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    kind: Mapped[str] = mapped_column(String(16))
    item_id: Mapped[str] = mapped_column(String(64))
    cloud_title: Mapped[str] = mapped_column(String(128), default="")
    cloud_content: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    cloud_checksum: Mapped[str] = mapped_column(String(64), default="")
    cloud_deleted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    device_title: Mapped[str] = mapped_column(String(128), default="")
    device_content: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    device_checksum: Mapped[str] = mapped_column(String(64), default="")
    device_id: Mapped[str | None] = mapped_column(String(32), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False
    )
